"""Draws the widget's animated microphone, one vector file per frame.

An Android widget cannot run animation code: the home screen draws it from a
description, and the only things that move on their own are a few stock views.
A ViewFlipper cycling through pre-drawn frames is the one that gives a smooth,
loopable picture, so the loop is drawn here and the widget layout flips
through it.

Run from the `android` folder:   python tools/make_widget_frames.py

Each frame is the app's own record button in miniature: a mint disc with five
ink bars that breathe as a wave travels across them, and a ring that swells and
fades once per loop. FRAMES x the layout's flipInterval is the loop length.
"""

import math
import os

FRAMES = 12
BAR_X = [17.0, 20.5, 24.0, 27.5, 31.0]
OUT = os.path.join(os.path.dirname(__file__), "..", "app", "src", "main", "res", "drawable")


def frame(t: int) -> str:
    p = t / FRAMES
    heights = [2.4 + 7.0 * (0.5 + 0.5 * math.sin(2 * math.pi * p - i * 0.95)) for i in range(5)]
    bars = "".join(f"M{x:.1f},{24 - h:.2f}L{x:.1f},{24 + h:.2f}" for x, h in zip(BAR_X, heights))
    r = 19.0 + 4.6 * p
    alpha = 0.7 * (1 - p) ** 1.3
    ring = f"M{24 - r:.2f},24a{r:.2f},{r:.2f} 0 1,0 {2 * r:.2f},0a{r:.2f},{r:.2f} 0 1,0 -{2 * r:.2f},0"
    disc = "M24,24m-17.5,0a17.5,17.5 0 1,0 35,0a17.5,17.5 0 1,0 -35,0"
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/make_widget_frames.py: frame {t + 1} of {FRAMES} of the widget's microphone. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="72dp"
    android:height="72dp"
    android:viewportWidth="48"
    android:viewportHeight="48">
    <path
        android:fillColor="#00000000"
        android:pathData="{ring}"
        android:strokeAlpha="{alpha:.2f}"
        android:strokeColor="#CFEAD9"
        android:strokeWidth="1.3" />
    <path
        android:fillColor="#CFEAD9"
        android:pathData="{disc}" />
    <path
        android:fillColor="#00000000"
        android:pathData="{bars}"
        android:strokeColor="#1A1A1A"
        android:strokeLineCap="round"
        android:strokeWidth="2.5" />
</vector>
'''


if __name__ == "__main__":
    os.makedirs(OUT, exist_ok=True)
    for t in range(FRAMES):
        with open(os.path.join(OUT, f"widget_wave_{t:02d}.xml"), "w", encoding="utf8") as f:
            f.write(frame(t))
    print(f"wrote {FRAMES} frames to {os.path.normpath(OUT)}")
