"""Draws the widget's microphone in every state, one vector file each.

An Android widget cannot run animation code: the home screen draws it from a
description, and the one thing that moves on its own is a ViewFlipper cycling
through pre-drawn frames. So the two moving states (listening, reading) are
drawn here as loops, and the still states as single pictures.

Everything follows docs/DESIGN.md: flat colour, a 2px ink border, no shadow or
glow. Mint is the idle button, Ember Glow means the microphone is live (and
nothing else), forest ink is "done", the alert red is "it failed".

Run from the `android` folder:   python tools/make_widget_frames.py
"""

import math
import os

FRAMES = 12
BAR_X = [17.0, 20.5, 24.0, 27.5, 31.0]
OUT = os.path.join(os.path.dirname(__file__), "..", "app", "src", "main", "res", "drawable")

INK, MINT, EMBER, FOREST, PAPER, FOG, ALERT, RAISED = (
    "#1A1A1A", "#CFEAD9", "#FFA946", "#034F46", "#F0EDE7", "#615D57", "#9E3521", "#F9F7F3")

HEAD = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/make_widget_frames.py: {what}. -->\n'
OPEN = ('<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="72dp"\n    android:height="72dp"\n'
        '    android:viewportWidth="48"\n    android:viewportHeight="48">\n')

DISC = "M24,24m-20.5,0a20.5,20.5 0 1,0 41,0a20.5,20.5 0 1,0 -41,0"


def path(data, fill=None, stroke=None, width=None, alpha=None, cap=None):
    out = "    <path\n"
    if alpha is not None:
        out += f'        android:fillAlpha="{alpha}"\n'
    out += f'        android:fillColor="{fill or "#00000000"}"\n'
    out += f'        android:pathData="{data}"\n'
    if stroke:
        if cap:
            out += f'        android:strokeLineCap="{cap}"\n        android:strokeLineJoin="round"\n'
        out += f'        android:strokeColor="{stroke}"\n        android:strokeWidth="{width}"'
        out += " />\n"
    else:
        out = out.rstrip("\n") + " />\n"
    return out


def bars(heights, color=INK):
    d = "".join(f"M{x:.1f},{24 - h:.2f}L{x:.1f},{24 + h:.2f}" for x, h in zip(BAR_X, heights))
    return path(d, stroke=color, width=2.7, cap="round")


def button(fill, heights, alpha=None):
    """The record button's disc: flat fill, 2px ink border, ink bars."""
    return (path(DISC, fill=fill, alpha=alpha)
            + path(DISC, stroke=INK, width=1.8)
            + bars(heights))


def write(name, body, what):
    with open(os.path.join(OUT, name + ".xml"), "w", encoding="utf8") as f:
        f.write(HEAD.format(what=what) + OPEN + body + "</vector>\n")


REST = [3.0, 5.8, 8.0, 5.8, 3.0]


def listening(t):
    p = t / FRAMES
    return [2.4 + 7.0 * (0.5 + 0.5 * math.sin(2 * math.pi * p - i * 0.95)) for i in range(5)]


def reading(t):
    p = t / FRAMES
    return [2.6 + 5.0 * (0.5 + 0.5 * math.sin(2 * math.pi * p - i * 1.25)) for i in range(5)]


if __name__ == "__main__":
    os.makedirs(OUT, exist_ok=True)
    write("widget_mic_idle", button(MINT, REST), "idle: the mint record button")
    write("widget_mic_warm", button(EMBER, REST, alpha="0.8"), "warming: ember at 80%, as in the app")
    for t in range(FRAMES):
        write(f"widget_rec_{t:02d}", button(EMBER, listening(t)), f"listening, frame {t + 1} of {FRAMES}")
        write(f"widget_read_{t:02d}", button(MINT, reading(t)), f"reading it back, frame {t + 1} of {FRAMES}")

    # Logged: forest ink with a paper tick. Drawn at 80% so the tile's Undo
    # button, in the corner, has room.
    group = "\n".join([
        '    <group',
        '        android:pivotX="24"',
        '        android:pivotY="24"',
        '        android:scaleX="0.8"',
        '        android:scaleY="0.8">',
        '',
    ])
    write("widget_mic_saved",
          group + path(DISC, fill=FOREST) + path(DISC, stroke=INK, width=1.8)
          + path("M15.5,24.5L21.5,30.5L33,18", stroke=PAPER, width=3.2, cap="round")
          + "    </group>\n",
          "logged: forest ink and a tick")
    # Check this: paper, an ink outline, a question mark in fog.
    write("widget_mic_check",
          path(DISC, fill=RAISED) + path(DISC, stroke=INK, width=1.8)
          + path("M19.2,19.5C19.6,16.2 21.8,14.6 24.4,14.6C27.3,14.6 29.2,16.4 29.2,18.9C29.2,22.6 24.4,22.6 24.4,27", stroke=FOG, width=2.8, cap="round")
          + path("M24.4,32.4L24.4,32.6", stroke=FOG, width=3.4, cap="round"),
          "check this: a question mark")
    # Failed: paper, an alert-red outline, an exclamation mark.
    write("widget_mic_fail",
          path(DISC, fill=RAISED) + path(DISC, stroke=ALERT, width=1.8)
          + path("M24,14.5L24,26", stroke=ALERT, width=3.2, cap="round")
          + path("M24,32L24,32.2", stroke=ALERT, width=3.6, cap="round"),
          "failed: an exclamation mark")
    print("wrote the widget drawings to", os.path.normpath(OUT))
